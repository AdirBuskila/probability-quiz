# -*- coding: utf-8 -*-
"""Writes courses/which_model/C01.js .. C09.js from defs.py + lessons.py.   PYTHONUTF8=1 py build.py"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from defs import PROBLEMS, BOSS, BOSS_RECAP  # noqa: E402
from lessons import LEVELS, LESSONS  # noqa: E402

OUT = HERE.parents[3] / "courses" / "which_model"
IDS = "abcd"


def js(x):
    return json.dumps(x, ensure_ascii=False)


def level_questions(level):
    qs, n = [], 0
    for pi, p in enumerate([p for p in PROBLEMS if p["level"] == level]):
        sim = dict(p["sim"])
        sim["exact"] = p["ans"]
        sim = {"kind": sim["kind"], "estimate": sim["estimate"], "exact": sim["exact"], "params": sim["params"]}
        pos = pi % 4                                   # where the right option sits
        order = list(range(4))
        order.remove(0)
        order.insert(pos, 0)                           # option 0 (the right one) goes to slot `pos`
        options = [{"id": IDS[slot], "value": p["opts"][i][0]} for slot, i in enumerate(order)]
        correct = IDS[pos]
        right = p["opts"][0]
        why = f"**{right[0]}**: {right[1]}\nלמה לא האחרות:\n" + "\n".join(f"✗ {o[0]}: {o[1]}" for o in p["opts"][1:])
        story = p["story"]

        def add(step, recap):
            nonlocal n
            n += 1
            qs.append({"id": f"wm-C{level:02d}-Q{n}", "step": step, "sim": sim, "recap": recap})

        add({"type": "choice", "prompt": story + "\n\n" + p["ask"], "options": options, "correctId": correct, "explain": why}, p["recap"])
        if p.get("param"):
            pr = p["param"]
            add({"type": "numeric", "prompt": story + "\n\n" + pr["prompt"], "answer": pr["ans"], "tol": pr["tol"], "explain": pr["explain"]}, p["recap"])
        add({"type": "numeric", "prompt": story + "\n\n" + p["final"], "answer": round(p["ans"], 4), "tol": p["tol"], "explain": p["calc"]}, p["recap"])
    return qs


def render(level):
    meta = LEVELS[level]
    boss = level == 9
    if boss:
        qs = [{"bankId": b, "recap": BOSS_RECAP[b]} for b in BOSS]
    else:
        qs = level_questions(level)
    lines = [f"/* which_model, level {level}. Generated by tools/verify/needhelp/which_model/build.py; checked by check.py */",
             'COURSE_LEVEL("which_model", {',
             f"  id: {js('C%02d' % level)}, order: {level}, icon: {js(meta['icon'])}, title: {js(meta['title'])},",
             f"  goal: {js(meta['goal'])},"]
    if boss:
        lines.append("  boss: true,")
    lines.append('  source: "ai-verified",')
    html = LESSONS[level]
    assert "`" not in html and "${" not in html
    lines.append("  lesson: { html: String.raw`" + html + "` },")
    lines.append("  questions: [")
    for q in qs:
        lines.append("    " + js(q) + ",")
    lines.append("  ],")
    lines.append("});")
    return "\n".join(lines) + "\n"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for level in range(1, 10):
        (OUT / f"C{level:02d}.js").write_text(render(level), encoding="utf-8", newline="\n")
    print("wrote", len(list(OUT.glob("C0*.js"))), "levels to", OUT)


if __name__ == "__main__":
    main()
