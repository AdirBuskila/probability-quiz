"""Every problem of the which_model course. Read by build.py (writes courses/which_model/C0N.js) and check.py.

A problem = a short word problem. Its first question is a `choice` step ("which model or tool?"), then an optional
parameter step, then a numeric step. Each option: (label, reason, alt) -- the first option is the right one (alt None);
for a wrong model `alt` is the answer THAT model would give on this problem (check.py asserts it differs).
`mc(rng)` simulates the story itself and returns one number per trial (None = trial rejected by a condition).
"""
