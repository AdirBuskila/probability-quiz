# ---------------------------------------------------------------- numbers (verified)
TE = w.Pa(w.N(w.S(w.N(w.Pa(w.C("A"), w.C("B")), "ab"), w.C("C")), "abc"), w.C("D"))
PRE = {"A": Fr("0.6"), "B": Fr("0.5"), "C": Fr("0.9"), "D": Fr("0.6")}
b_ab = 1 - (1 - PRE["A"]) * (1 - PRE["B"])
b_abc = b_ab * PRE["C"]
b_all = 1 - (1 - b_abc) * (1 - PRE["D"])
assert (b_ab, b_abc, b_all) == (Fr("0.8"), Fr("0.72"), Fr("0.888"))
assert w.fprob(lambda s: w.works(TE, s), PRE) == b_all                 # block reduction = full truth table
WRONG = 1 - (1 - PRE["A"]) * (1 - PRE["B"]) * (1 - PRE["C"]) * (1 - PRE["D"])
assert WRONG != b_all                                                   # "everything in parallel" is wrong

# example 2: A in series with (B || (C series D)) at 0.9, 0.5, 0.8, 0.5
T2E = w.S(w.C("A"), w.N(w.Pa(w.C("B"), w.N(w.S(w.C("C"), w.C("D")), "cd")), "bcd"))
PR2 = {"A": Fr("0.9"), "B": Fr("0.5"), "C": Fr("0.8"), "D": Fr("0.5")}
c_cd = PR2["C"] * PR2["D"]
c_bcd = 1 - (1 - PR2["B"]) * (1 - c_cd)
c_all = PR2["A"] * c_bcd
assert (c_cd, c_bcd, c_all) == (Fr("0.4"), Fr("0.7"), Fr("0.63"))
assert w.fprob(lambda s: w.works(T2E, s), PR2) == c_all and c_all <= PR2["A"]

# exam-style (original): A || (B - (C || D)), all p
p = w.p
T2 = w.Pa(w.C("A"), w.N(w.S(w.C("B"), w.N(w.Pa(w.C("C"), w.C("D")), "cd")), "bcd"))
PQ2 = w.sprob(lambda s: w.works(T2, s), w.same("ABCD"))
assert w.eq(w.sprob(lambda s: s["C"] or s["D"], w.same("CD")), 2 * p - p ** 2)
assert w.eq(PQ2, 1 - (1 - p) * (1 - p * (2 * p - p ** 2))) and w.eq(PQ2, p + 2 * p ** 2 - 3 * p ** 3 + p ** 4)
assert not w.eq(PQ2, 1 - (1 - p) * (1 - p * 2 * p))                    # the trap: C||D as 2p
from fractions import Fraction as _F
assert all(PQ2.subs(p, _F(k, 10)) >= _F(k, 10) for k in range(1, 10))   # never below P(A): A is in parallel

