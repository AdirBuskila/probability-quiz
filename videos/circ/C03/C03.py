"""C03 · טור ומקביל ביחד — video script (build: tools/video/vid.py C03).

Source: courses/circ/C03.js (lesson + goal). Exam part: an original question in exam style (bank={}): A in parallel
with (B in series with C||D), all p: P(S) = 1-(1-p)(1-p(2p-p^2)) = p+2p^2-3p^3+p^4.
Why no bank anchor: the free series-parallel parts are 25A-A-Q4b (its P(Q2) = p^3(2-p)^2 is the denominator of the
C07 quiz item 25A-A-Q4c), 24A-B-Q6b (the denominator of the C09 boss item 24A-B-Q6c), 25B-B-Q5a / 24A-E-Q6a /
25S-B-Q5a (the (A-B)||C block of the quiz item 24B-A-Q6a) and 24B-B-Q6b (used in C07).
Avoided on purpose: every C03 quiz case (AB||CD at 0.9, (A||B)(C||D) at 0.5, (A||B)C as a formula, AB||C at
0.5/0.5/0.8, 25B-A-Q5a p(2p-p^2), 24B-A-Q6a D((AB)||C)) and the lesson's A(B||C) at 0.9/0.8/0.8;
25A-A-Q4b (see above).
Worked examples: A(B||CD) at 0.9/0.5/0.8/0.5 = 0.63; ((A||B) in series with C) || D at A=0.6, B=0.5, C=0.9, D=0.6: 0.8 -> 0.72 -> 0.888.
Every number is exact (Fractions / sympy over the full truth table, w_circ).
"""
from fractions import Fraction as Fr
from vid import P, Scene, Video, show, hide, BANK
