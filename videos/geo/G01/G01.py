# ---------------------------------------------------------------- numbers (verified)
# example 1: unit square, X>1/3 and Y<3/4
A1 = g.area(g.clip([(1, 0, Fr(1, 3), ">"), (0, 1, Fr(3, 4), "<")], (0, 1), (0, 1)))
assert A1 == Fr(2, 3) * Fr(3, 4) == Fr(1, 2)
g.mc(lambda x, y: (x > 1 / 3) & (y < .75), (0, 1), (0, 1), A1)
assert A1 == (1 - Fr(1, 3)) * Fr(3, 4)                 # = P(X>1/3) P(Y<3/4): independence

# example 2: X~U(0,4), Y~U(0,1); 1<X<2 and Y>1/2
OM2 = 4 * 1
A2 = g.area(g.clip([(1, 0, 1, ">"), (1, 0, 2, "<"), (0, 1, Fr(1, 2), ">")], (0, 4), (0, 1)))
assert A2 == Fr(1, 2) and A2 / OM2 == Fr(1, 8)
g.mc(lambda x, y: (x > 1) & (x < 2) & (y > .5), (0, 4), (0, 1), A2 / OM2)

# exam 24B-B-Q1a, in units of L: X1~U(0,1), X2~U(0,2)
Q = BANK["24B-B-Q1a"]
assert "L/5" in Q["question"] and Q["contextId"] == "24B-B-c1" and "\\frac15" in Q["solution"].replace(" ", "")
OM = 1 * 2                                             # |Omega| = L * 2L = 2 L^2
AX = g.area(g.clip([(1, 0, Fr(1, 5), "<")], (0, 1), (0, 2)))
assert AX == Fr(2, 5) and AX / OM == Fr(1, 5)          # strip L/5 wide, 2L high
assert AX / 1 == Fr(2, 5)                              # the trap: dividing by L^2
g.mc(lambda x, y: x < .2, (0, 1), (0, 2), Fr(1, 5))
AY = g.area(g.clip([(0, 1, Fr(1, 5), "<")], (0, 1), (0, 2)))
assert AY == Fr(1, 5) and AY / OM == Fr(1, 10)         # the original follow-up: P(X2<L/5)
g.mc(lambda x, y: y < .2, (0, 1), (0, 2), Fr(1, 10))

